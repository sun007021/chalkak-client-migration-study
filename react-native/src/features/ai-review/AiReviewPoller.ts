/**
 * AI 피드백 상태 확인·폴링(PR8에서 구현, D-03: 3초 간격 300초 창, 화면이 보일 때만).
 * 홈은 "보일 때 시작, 안 보이면 멈춤"만 호출한다. 카드의 문구·요청·폴링 로직은 AI 리뷰 영역이다.
 */
export interface AiReviewPoller {
  /** 이 게시물의 상태를 GET부터 확인하고 필요하면 폴링한다. 같은 게시물로 다시 부르면 새 창을 시작한다. */
  start(postId: string): void;
  /** 폴링을 멈춘다(화면 이탈, 카드 사라짐). 결과 상태는 지우지 않는다. */
  stop(): void;
}
